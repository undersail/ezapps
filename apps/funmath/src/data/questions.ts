/** 题库索引（按 id 快速查） */
export const questionMap: Record<string, Question> = questions.reduce(
  (acc, q) => {
    acc[q.id] = q
    return acc
  },
  {} as Record<string, Question>,
)

/** 通过题目 ID 列表获取完整题目 */
export function getQuestionsByIds(ids: string[]): Question[] {
  return ids.map((id) => questionMap[id]).filter(Boolean)
}